      IMPORT :: C_CHAR,C_INT,C_DOUBLE
      CHARACTER(KIND=C_CHAR), DIMENSION(*) :: MESH
      INTEGER(C_INT) :: N
      REAL(C_DOUBLE), DIMENSION(*) :: COORDS
