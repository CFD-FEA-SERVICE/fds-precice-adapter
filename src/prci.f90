CONTAINS


!> \brief Read the &PRCI line and flag the coupled SURFaces. Call after READ_DATA.

SUBROUTINE READ_PRCI

CHARACTER(LABEL_LENGTH) :: PARTICIPANT,MESH_NAME,SURF_ID(MAX_COUPLED_SURF),COUPLING_MODE,TEMPERATURE_UNIT, &
                           FLUX_DATA_NAME,TEMPERATURE_DATA_NAME,SINK_TEMPERATURE_DATA_NAME,HTC_DATA_NAME
CHARACTER(FN_LENGTH) :: CONFIG_FILE
LOGICAL :: FLUX_INTO_SOLID_POSITIVE
INTEGER :: IOS,N,NS,N_FOUND
TYPE(SURFACE_TYPE), POINTER :: SF
NAMELIST /PRCI/ PARTICIPANT,CONFIG_FILE,MESH_NAME,SURF_ID,COUPLING_MODE,TEMPERATURE_UNIT,FLUX_DATA_NAME, &
                TEMPERATURE_DATA_NAME,SINK_TEMPERATURE_DATA_NAME,HTC_DATA_NAME,FLUX_INTO_SOLID_POSITIVE

PARTICIPANT='Fluid' ; CONFIG_FILE='precice-config.xml' ; MESH_NAME='Fluid-Mesh' ; SURF_ID='null'
COUPLING_MODE='DIRICHLET' ; TEMPERATURE_UNIT='K'
FLUX_DATA_NAME='Heat-Flux' ; TEMPERATURE_DATA_NAME='Temperature'
SINK_TEMPERATURE_DATA_NAME='Sink-Temperature' ; HTC_DATA_NAME='Heat-Transfer-Coefficient'
FLUX_INTO_SOLID_POSITIVE=.TRUE.

REWIND(LU_INPUT) ; INPUT_FILE_LINE_NUMBER = 0
N_FOUND = 0
PRCI_LOOP: DO
   CALL CHECKREAD('PRCI',LU_INPUT,IOS) ; IF (STOP_STATUS==SETUP_STOP) RETURN
   IF (IOS==1) EXIT PRCI_LOOP
   READ(LU_INPUT,PRCI,END=11,ERR=12,IOSTAT=IOS)
   N_FOUND = N_FOUND + 1
   12 IF (IOS>0) THEN ; CALL SHUTDOWN('ERROR(PRCI-1): Problem with PRCI line') ; RETURN ; ENDIF
ENDDO PRCI_LOOP
11 REWIND(LU_INPUT) ; INPUT_FILE_LINE_NUMBER = 0

IF (N_FOUND==0) RETURN
IF (N_FOUND>1) THEN ; CALL SHUTDOWN('ERROR(PRCI-2): Only one PRCI line is allowed') ; RETURN ; ENDIF

PRECICE_COUPLING = .TRUE.
P_PARTICIPANT = PARTICIPANT ; P_CONFIG = CONFIG_FILE ; P_MESH = MESH_NAME
P_DATA_FLUX = FLUX_DATA_NAME ; P_DATA_TEMP = TEMPERATURE_DATA_NAME
P_DATA_SINK = SINK_TEMPERATURE_DATA_NAME ; P_DATA_HTC = HTC_DATA_NAME
FLUX_SIGN = 1._EB ; IF (.NOT.FLUX_INTO_SOLID_POSITIVE) FLUX_SIGN = -1._EB

SELECT CASE(TRIM(COUPLING_MODE))
   CASE('DIRICHLET') ; COUPLING_MODE_INDEX = MODE_DIRICHLET
   CASE('ROBIN')     ; COUPLING_MODE_INDEX = MODE_ROBIN
   CASE DEFAULT
      CALL SHUTDOWN('ERROR(PRCI-3): COUPLING_MODE must be DIRICHLET or ROBIN') ; RETURN
END SELECT

SELECT CASE(TRIM(TEMPERATURE_UNIT))
   CASE('K') ; T_OFFSET = 0._EB
   CASE('C') ; T_OFFSET = TMPM
   CASE DEFAULT
      CALL SHUTDOWN('ERROR(PRCI-4): TEMPERATURE_UNIT must be K or C') ; RETURN
END SELECT

! Flag the coupled surfaces. They must be SPECIFIED_TEMPERATURE surfaces (TMP_FRONT given, no MATL_ID):
! TMP_FRONT is the surface temperature used until the structural solver provides one.

NS = 0
DO N=1,MAX_COUPLED_SURF
   IF (SURF_ID(N)=='null') CYCLE
   NS = NS + 1
   IF (.NOT.FLAG_SURF(SURF_ID(N))) THEN
      CALL SHUTDOWN('ERROR(PRCI-5): SURF_ID '//TRIM(SURF_ID(N))//' on PRCI line not found') ; RETURN
   ENDIF
ENDDO
IF (NS==0) THEN ; CALL SHUTDOWN('ERROR(PRCI-6): PRCI line needs at least one SURF_ID') ; RETURN ; ENDIF

CONTAINS

LOGICAL FUNCTION FLAG_SURF(ID)
CHARACTER(*), INTENT(IN) :: ID
INTEGER :: I
FLAG_SURF = .FALSE.
DO I=1,N_SURF
   SF => SURFACE(I)
   IF (SF%ID/=ID) CYCLE
   IF (SF%THERMAL_BC_INDEX/=SPECIFIED_TEMPERATURE) THEN
      CALL SHUTDOWN('ERROR(PRCI-7): coupled SURF '//TRIM(ID)//' must have TMP_FRONT and no MATL_ID')
      FLAG_SURF = .TRUE. ; RETURN
   ENDIF
   SF%PRECICE_COUPLED = .TRUE.
   FLAG_SURF = .TRUE.
ENDDO
END FUNCTION FLAG_SURF

END SUBROUTINE READ_PRCI


!> \brief Create the participant, define the coupling mesh from the coupled WALL cells and initialize preCICE.

SUBROUTINE PRECICE_INITIALIZE(T)

REAL(EB), INTENT(IN) :: T
INTEGER :: NM,IW,I
INTEGER(C_INT) :: RANK,NPROC,DIM,NN,FLAG
REAL(C_DOUBLE) :: DTMAX
TYPE(MESH_TYPE), POINTER :: M
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_COORD_TYPE), POINTER :: BC

RANK  = MY_RANK
NPROC = N_MPI_PROCESSES
CALL PRECICEF_CREATE(CS(P_PARTICIPANT),CS(P_CONFIG),RANK,NPROC,LEN_TRIM(P_PARTICIPANT),LEN_TRIM(P_CONFIG))

CALL PRECICEF_GET_MESH_DIMENSIONS(CS(P_MESH),DIM,LEN_TRIM(P_MESH))
IF (DIM/=3) THEN ; CALL SHUTDOWN('ERROR(PRCI-8): the preCICE mesh must be 3-D',PROCESS_0_ONLY=.FALSE.) ; RETURN ; ENDIF

! Count and store the coupled WALL cells owned by this process

N_V = 0
DO I=1,2
   DO NM=LOWER_MESH_INDEX,UPPER_MESH_INDEX
      M => MESHES(NM)
      DO IW=1,M%N_EXTERNAL_WALL_CELLS+M%N_INTERNAL_WALL_CELLS
         IF (.NOT.IS_COUPLED(M,IW)) CYCLE
         N_V = N_V + 1
         IF (I==2) THEN
            WC => M%WALL(IW)
            BC => M%BOUNDARY_COORD(WC%BC_INDEX)
            V_MESH(N_V) = NM
            V_WALL(N_V) = IW
            V_COORD(3*N_V-2:3*N_V) = (/BC%X,BC%Y,BC%Z/)
         ENDIF
      ENDDO
   ENDDO
   IF (I==1) THEN
      ALLOCATE(V_MESH(N_V),V_WALL(N_V),V_IDS(N_V),V_COORD(3*N_V),ACC_1(N_V),ACC_2(N_V),BUF_1(N_V),BUF_2(N_V),BUF_T(N_V))
      N_V = 0
   ENDIF
ENDDO

NN = N_V
CALL PRECICEF_SET_VERTICES(CS(P_MESH),NN,V_COORD,V_IDS,LEN_TRIM(P_MESH))
WRITE(LU_ERR,'(A,I0,A,I0,A)') ' preCICE: MPI process ',MY_RANK,' couples ',N_V,' WALL cells'

ACC_1 = 0._EB ; ACC_2 = 0._EB ; T_WINDOW_ACC = 0._EB ; T_PREV = T

CALL PRECICEF_REQUIRES_INITIAL_DATA(FLAG)
IF (FLAG==1) THEN
   CALL INSTANT_VALUES(BUF_1,BUF_2)
   CALL WRITE_VALUES(BUF_1,BUF_2)
ENDIF

CALL PRECICEF_INITIALIZE()

CALL PRECICEF_GET_MAX_TIME_STEP_SIZE(DTMAX)
CALL READ_TEMPERATURE(0._EB)

END SUBROUTINE PRECICE_INITIALIZE


!> \brief Clip the FDS time step so that FDS never steps over the end of a preCICE time window

SUBROUTINE PRECICE_LIMIT_TIME_STEP(DT)

REAL(EB), INTENT(INOUT) :: DT
REAL(C_DOUBLE) :: DTMAX

IF (.NOT.COUPLING_ONGOING) RETURN
CALL PRECICEF_GET_MAX_TIME_STEP_SIZE(DTMAX)
IF (DTMAX>0._EB) DT = MIN(DT,REAL(DTMAX,EB))

END SUBROUTINE PRECICE_LIMIT_TIME_STEP


!> \brief Called once per completed FDS time step: accumulate, write, advance, read

SUBROUTINE PRECICE_ADVANCE(T,DT_NEXT,T_END)

REAL(EB), INTENT(IN) :: T,DT_NEXT
REAL(EB), INTENT(INOUT) :: T_END
REAL(EB) :: DT_TAKEN
REAL(C_DOUBLE) :: DTC,DTMAX
INTEGER(C_INT) :: FLAG

IF (.NOT.COUPLING_ONGOING) RETURN

DT_TAKEN = T - T_PREV
T_PREV   = T
IF (DT_TAKEN<=0._EB) RETURN

! Time-weighted window average of the data to be written

CALL INSTANT_VALUES(BUF_1,BUF_2)
ACC_1 = ACC_1 + BUF_1*DT_TAKEN
ACC_2 = ACC_2 + BUF_2*DT_TAKEN
T_WINDOW_ACC = T_WINDOW_ACC + DT_TAKEN
IF (COUPLING_MODE_INDEX==MODE_ROBIN) THEN
   ! Average the heat flux at the sink temperature consistently: store h and h*T_sink
   BUF_2 = ACC_2/T_WINDOW_ACC
   BUF_1 = ACC_1/MAX(ACC_2,TWO_EPSILON_EB)
ELSE
   BUF_1 = ACC_1/T_WINDOW_ACC
ENDIF
CALL WRITE_VALUES(BUF_1,BUF_2)

DTC = DT_TAKEN
CALL PRECICEF_ADVANCE(DTC)

CALL PRECICEF_IS_TIME_WINDOW_COMPLETE(FLAG)
IF (FLAG==1) THEN
   ACC_1 = 0._EB ; ACC_2 = 0._EB ; T_WINDOW_ACC = 0._EB
ENDIF

CALL PRECICEF_IS_COUPLING_ONGOING(FLAG)
IF (FLAG==0) THEN
   COUPLING_ONGOING = .FALSE.
   IF (T<T_END) THEN
      IF (MY_RANK==0) WRITE(LU_ERR,'(A,F10.3,A)') ' preCICE: coupling ended at t=',T,' s; stopping FDS'
      T_END = T
   ENDIF
   RETURN
ENDIF

CALL PRECICEF_GET_MAX_TIME_STEP_SIZE(DTMAX)
CALL READ_TEMPERATURE(MIN(DT_NEXT,REAL(DTMAX,EB)))

END SUBROUTINE PRECICE_ADVANCE


SUBROUTINE PRECICE_FINALIZE
IF (.NOT.PRECICE_COUPLING) RETURN
CALL PRECICEF_FINALIZE()
END SUBROUTINE PRECICE_FINALIZE


! ---------------------------------------------------------------------------------------------------------------------------------

!> \brief Instantaneous values of the written data. DIRICHLET: VAL_1 = net flux into solid (W/m2).
!> ROBIN: VAL_1 = h_eff*T_sink (W/m2), VAL_2 = h_eff (W/m2/K), so that the window average of T_sink is h-weighted.

SUBROUTINE INSTANT_VALUES(VAL_1,VAL_2)

REAL(EB), INTENT(OUT) :: VAL_1(:),VAL_2(:)
INTEGER :: I
REAL(EB) :: HC,HR,TR,TS,TG
TYPE(MESH_TYPE), POINTER :: M
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

DO I=1,N_V
   M  => MESHES(V_MESH(I))
   WC => M%WALL(V_WALL(I))
   B1 => M%BOUNDARY_PROP1(WC%B1_INDEX)
   SELECT CASE(COUPLING_MODE_INDEX)
      CASE(MODE_DIRICHLET)
         VAL_1(I) = FLUX_SIGN*(B1%Q_CON_F + B1%Q_RAD_IN - B1%Q_RAD_OUT)
         VAL_2(I) = 0._EB
      CASE(MODE_ROBIN)
         TS = B1%TMP_F
         TG = B1%TMP_G
         HC = MAX(B1%HEAT_TRANS_COEF,TWO_EPSILON_EB)
         ! Radiation temperature from the absorbed incident flux, then linearised radiative h
         TR = (MAX(B1%Q_RAD_IN,0._EB)/(MAX(B1%EMISSIVITY,TWO_EPSILON_EB)*SIGMA))**0.25_EB
         HR = B1%EMISSIVITY*SIGMA*(TS**2+TR**2)*(TS+TR)
         VAL_2(I) = HC + HR
         VAL_1(I) = HC*TG + HR*TR
   END SELECT
ENDDO

END SUBROUTINE INSTANT_VALUES


SUBROUTINE WRITE_VALUES(VAL_1,VAL_2)
REAL(EB), INTENT(IN) :: VAL_1(:),VAL_2(:)
INTEGER(C_INT) :: NN
NN = N_V
SELECT CASE(COUPLING_MODE_INDEX)
   CASE(MODE_DIRICHLET)
      BUF_T = VAL_1
      CALL PRECICEF_WRITE_DATA(CS(P_MESH),CS(P_DATA_FLUX),NN,V_IDS,BUF_T,LEN_TRIM(P_MESH),LEN_TRIM(P_DATA_FLUX))
   CASE(MODE_ROBIN)
      BUF_T = VAL_1 - T_OFFSET
      CALL PRECICEF_WRITE_DATA(CS(P_MESH),CS(P_DATA_SINK),NN,V_IDS,BUF_T,LEN_TRIM(P_MESH),LEN_TRIM(P_DATA_SINK))
      BUF_T = VAL_2
      CALL PRECICEF_WRITE_DATA(CS(P_MESH),CS(P_DATA_HTC),NN,V_IDS,BUF_T,LEN_TRIM(P_MESH),LEN_TRIM(P_DATA_HTC))
END SELECT
END SUBROUTINE WRITE_VALUES


!> \brief Read the solid surface temperature and impose it on the coupled WALL cells

SUBROUTINE READ_TEMPERATURE(REL_TIME)

REAL(EB), INTENT(IN) :: REL_TIME
REAL(C_DOUBLE) :: RT
INTEGER(C_INT) :: NN
INTEGER :: I
TYPE(MESH_TYPE), POINTER :: M
TYPE(WALL_TYPE), POINTER :: WC
TYPE(BOUNDARY_PROP1_TYPE), POINTER :: B1

NN = N_V ; RT = REL_TIME
CALL PRECICEF_READ_DATA(CS(P_MESH),CS(P_DATA_TEMP),NN,V_IDS,RT,BUF_T,LEN_TRIM(P_MESH),LEN_TRIM(P_DATA_TEMP))

DO I=1,N_V
   M  => MESHES(V_MESH(I))
   WC => M%WALL(V_WALL(I))
   B1 => M%BOUNDARY_PROP1(WC%B1_INDEX)
   ! A zero (never written) value keeps the current temperature (TMP_FRONT at start)
   IF (BUF_T(I)+T_OFFSET>1._EB) B1%TMP_F = BUF_T(I) + T_OFFSET
ENDDO

END SUBROUTINE READ_TEMPERATURE


LOGICAL FUNCTION IS_COUPLED(M,IW)
TYPE(MESH_TYPE), INTENT(IN) :: M
INTEGER, INTENT(IN) :: IW
IS_COUPLED = .FALSE.
IF (M%WALL(IW)%BOUNDARY_TYPE/=SOLID_BOUNDARY) RETURN
IF (M%WALL(IW)%B1_INDEX<=0 .OR. M%WALL(IW)%BC_INDEX<=0) RETURN
IS_COUPLED = SURFACE(M%WALL(IW)%SURF_INDEX)%PRECICE_COUPLED
END FUNCTION IS_COUPLED


!> \brief Trimmed character array for the C interface (lengths are passed separately)

FUNCTION CS(S) RESULT(A)
CHARACTER(*), INTENT(IN) :: S
CHARACTER(KIND=C_CHAR), DIMENSION(MAX(1,LEN_TRIM(S))) :: A
INTEGER :: I
A = ' '
DO I=1,LEN_TRIM(S)
   A(I) = S(I:I)
ENDDO
END FUNCTION CS

END MODULE PRECICE_ADAPTER
