!> \brief preCICE adapter for FDS (thermal surface coupling)
!>
!> FDS acts as the fluid/fire participant of a partitioned conjugate heat transfer problem.
!> On every WALL cell of a coupled SURF it can
!>   - write the net heat flux into the solid (convective + absorbed radiative - emitted radiative), and read the
!>     surface temperature computed by the structural solver  (COUPLING_MODE='DIRICHLET', default), or
!>   - write a sink temperature and an effective heat transfer coefficient (convection + linearised radiation)
!>     and read the surface temperature (COUPLING_MODE='ROBIN').
!>
!> FDS sub-cycles inside each preCICE time window. Only explicit coupling schemes are supported (no checkpointing).
!> Written data are averaged over the time window to filter the LES fluctuations.
!>
!> Input (one line in the .fds file):
!>   &PRCI PARTICIPANT='Fluid', CONFIG_FILE='../precice-config.xml', MESH_NAME='Fluid-Mesh',
!>         SURF_ID='COUPLED', COUPLING_MODE='DIRICHLET', TEMPERATURE_UNIT='K' /
!>
!> Copyright CFD FEA SERVICE SRL. Released under the same terms as FDS (public domain where applicable).

MODULE PRECICE_ADAPTER

USE ISO_C_BINDING
USE PRECISION_PARAMETERS
USE GLOBAL_CONSTANTS
USE MESH_VARIABLES
USE TYPES
USE COMP_FUNCTIONS, ONLY: CHECKREAD,SHUTDOWN

IMPLICIT NONE (TYPE,EXTERNAL)
PRIVATE

PUBLIC :: PRECICE_COUPLING,READ_PRCI,PRECICE_INITIALIZE,PRECICE_LIMIT_TIME_STEP,PRECICE_ADVANCE,PRECICE_FINALIZE

INTEGER, PARAMETER :: MAX_COUPLED_SURF=20
INTEGER, PARAMETER :: MODE_DIRICHLET=1,MODE_ROBIN=2

LOGICAL :: PRECICE_COUPLING=.FALSE.          !< True if a &PRCI line is present
INTEGER :: COUPLING_MODE_INDEX=MODE_DIRICHLET
CHARACTER(LABEL_LENGTH) :: P_PARTICIPANT='Fluid',P_MESH='Fluid-Mesh'
CHARACTER(LABEL_LENGTH) :: P_DATA_FLUX='Heat-Flux',P_DATA_TEMP='Temperature',P_DATA_SINK='Sink-Temperature',&
                           P_DATA_HTC='Heat-Transfer-Coefficient'
CHARACTER(FN_LENGTH) :: P_CONFIG='precice-config.xml'
REAL(EB) :: T_OFFSET=0._EB                   !< 0 for Kelvin, TMPM for Celsius exchange
REAL(EB) :: FLUX_SIGN=1._EB                  !< +1: positive flux enters the solid

INTEGER :: N_V=0                             !< Number of coupled WALL cells on this MPI process
INTEGER,  ALLOCATABLE, DIMENSION(:) :: V_MESH,V_WALL,V_IDS
REAL(EB), ALLOCATABLE, DIMENSION(:) :: V_COORD,ACC_1,ACC_2,BUF_1,BUF_2,BUF_T
REAL(EB) :: T_WINDOW_ACC=0._EB,T_PREV=0._EB
LOGICAL :: COUPLING_ONGOING=.TRUE.

